def test_相談者本人の言葉は止めん():
    """★守りが強すぎて正しい鑑定を弾いたら、それはそれで事故や。

    「気の抜けた四文字（おはよ〜）」は、まきこさん本人のLINEの話や。
    見本の「気の抜けへん運転」とは別もん。
    """
    body = "「おはよ〜」の、あの気の抜けた四文字から始まるやつや。"
    assert not kantei._example_leaks(body, "【相談者】まきこさん。")


def test_酒の相談なら酒の語は通す():
    """★見本が酒の話やからいうて、ほんまに酒の相談まで弾いたら使えん。"""
    det = "彼はアルコール依存で、酔ってお触り済みと言うとった。"
    assert not kantei._example_leaks("素面の時にその話をしてみ。", det)
    # ★酒の気配が一つも無い相談では、同じ語を弾く
    assert kantei._example_leaks("素面の時にその話をしてみ。", "彼は無口な人や。")


def test_見本を外す関数が指示を短うする():
    """書き直しの時に、見本の文ごと落とす仕組み。★指示が事実無しになった今も残す。"""
    ins = "①表の顔を書く。怜は店長や。②内側を書く。真翔は運転手や。③連絡の癖を書く。"
    got = kantei._strip_example_from_instruction(ins)
    assert "怜" not in got and "真翔" not in got
    assert "①表の顔を書く" in got
    assert "③連絡の癖を書く" in got
