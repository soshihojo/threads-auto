"""鑑定書に、別の一件の事実が混ざらんようにするための見張り。

★★★なんでこのテストが要るか。三度やらかしたからや。
  ・2026-08-15 あやかさん … 見本の相談者名が17回、第六章が丸ごと別人の話になった
  ・2026-08-28 はるちゃん … 骨格が言い換えられて入り込んだ
  ・2026-10-09 まきこさん … 第三章の仕事の段落が、ほぼ逐語で入った。
      相談者から「話してもないし事実とも違う出来事のせいで、
      よくわからない鑑定結果になってしまってる」と指摘が来た。金を貰うて渡した紙でや。

★守りは二段ある。どっちも効いとるかを、ここで見る。
  ① 入口 … 章の指示に、具体の事実を一つも置かん（CHAPTERS）
  ② 出口 … 出来上がった本文を、語で検査する（_example_leaks）
"""
import pytest

from src import kantei


# ---- ① 入口：章の指示に事実が無いこと ----

# 見本の一件に出てきた固有の事実。★一つでも指示に戻ってきたら、また漏れ始める
_EXAMPLE_FACTS_IN_PROMPT = (
    "怜", "真翔", "タンクローリー", "いわき", "七人の飲み会",
    "既読無視ごめん", "一方的でごめん", "期待には応えられない",
    "遊ぼー", "八番", "二十歳", "ファッション系", "店長",
    "三年前", "三年の空白", "十年", "十五年",
    "長い一人の時間", "不規則な勤務", "予定が分からん",
    "後悔の箱", "一線を越え", "告白の記憶",
)


@pytest.mark.parametrize("key,title,chars,instruction", kantei.CHAPTERS,
                         ids=[c[0] for c in kantei.CHAPTERS])
def test_章の指示に別の一件の事実が入ってへん(key, title, chars, instruction):
    """★ここが本丸や。指示が【台本】やった間は、似た相談者が来るたびに飲まれた。

    残してええんは「何をする章か」「どの順で書くか」「どこを深掘るか」だけ。
    具体の職業・地名・年数・台詞は、一つも置かん。
    """
    hit = [w for w in _EXAMPLE_FACTS_IN_PROMPT if w in instruction]
    assert not hit, (
        f"{key}（{title}）の指示に、別の一件の事実が戻っとる: {hit}\n"
        "★指示に事実を置いたら、似た相談者が来た時に必ず混ざる。"
        "書くんは『何をする章か』だけや。"
    )


@pytest.mark.parametrize("key,title,chars,instruction", kantei.CHAPTERS,
                         ids=[c[0] for c in kantei.CHAPTERS])
def test_無い項目は飛ばしてええと書いてある(key, title, chars, instruction):
    """★埋めさせようとするから、作り話が出る。

    「詳細に書いてあれば使う／無ければ飛ばす」が、どの章にも要る。
    これが無い章は、材料が薄い相談者が来た時に、埋めにいく。
    """
    assert any(w in instruction for w in ("飛ばす", "作らん", "書いてある時だけ",
                                          "書いてあれば", "無ければ")), (
        f"{key}（{title}）の指示に、"
        "『詳細に無い項目は飛ばしてええ』の断りが無い"
    )


def test_守ることの共通文に名前が残ってへん():
    """★全章の末尾に付く文や。ここに名前が残っとったら、全章に配られる。"""
    for key, title, _, ins in kantei.CHAPTERS:
        assert "怜" not in ins and "真翔" not in ins, f"{key} に名前が残っとる"


# ---- ② 出口：本文の検査 ----

def test_言い換えられた混入も止まる():
    """★2026-10-09 まきこさんの回で、実際に素通りした形や。

    網に「タンクローリー」はあったのに、
    【運転が絡む種類の仕事】と言い換えられて抜けた。
    """
    body = ("つかさの仕事は、長い一人の時間があって、勤務は不規則、"
            "しかも気の抜けへん運転が絡む種類の仕事や。"
            "あんたが三年前に言われたいう「予定が分からんから休みかどうか分からん」——"
            "あれは半分は事実でもあったはずや。")
    det = "【相談者】まきこさん。彼は酒を飲む。仕事が減った。"
    hits = kantei._example_leaks(body, det)
    assert hits, "言い換えられた混入が素通りしとる"
    assert "三年前" in hits
    assert "予定が分からん" in hits


