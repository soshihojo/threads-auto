def now_context() -> str:
    """プロンプトに渡す「今」の文脈（日付＋時刻＋時間帯）。

    ★2026-08-17：ここが「日付だけ」やったせいで、朝や昼に送る返信が
      「今日はもう寝なさい」「スマホ置いとき」「おやすみ」で締まる事故が続いた。
      椿は夜の相談を受ける前提の声（🌙・深夜に検索する読者）で書かれとるんで、
      時刻を渡さんかったら、生成は勝手に夜やと思い込む。
      実害（19件）：
        ・tomokoさん 8/16 11:21「今日は…寝とき。スマホは手の届かんとこ置いて」
        ・あやみさん 8/12 12:21「今は自分を責めるより、ちゃんと寝ときや🌙」
        ・yumichinさん 7/28 08:00「今日はもうスマホ置いとき」
      ★あわせて、素の datetime.now() をやめてJSTで固定する。
        サーバのタイムゾーンがUTCやと、日本時間の0〜9時に【今日の日付】が
        前日になる。日付を根拠に「昨日」「今日」を書く指示があるので、ここは効く。
    """
    n = datetime.now(JST)
    h = n.hour
    if 5 <= h < 11:
        band = "朝"
    elif 11 <= h < 17:
        band = "昼"
    elif 17 <= h < 21:
        band = "夕方から宵の口"
    elif 21 <= h < 24:
        band = "夜"
    else:
        band = "深夜"
    wd = "月火水木金土日"[n.weekday()]
    return f"{n.year}年{n.month}月{n.day}日（{wd}）{n.hour}時{n.minute:02d}分ごろ。今は{band}や"


