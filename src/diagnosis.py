# 二十七宿（昴宿から始まる標準配列）
SHUKU_27 = [
    "昴宿", "畢宿", "觜宿", "参宿", "井宿", "鬼宿", "柳宿", "星宿", "張宿",
    "翼宿", "軫宿", "角宿", "亢宿", "氐宿", "房宿", "心宿", "尾宿", "箕宿",
    "斗宿", "女宿", "虚宿", "危宿", "室宿", "壁宿", "奎宿", "婁宿", "胃宿",
]
_SPAN = 360.0 / 27.0  # 1宿あたりの黄経幅（約13.33度）

# 校正用オフセット（度）。公式宿曜表に合わせてここを調整する。
SHUKU_OFFSET_DEG = 0.0


def _days_since_j2000(d: datetime) -> float:
    """J2000.0(2000-01-01 12:00 UT)からの経過日数。出生時刻不明のため正午JST扱い。"""
    j2000 = datetime(2000, 1, 1, 12, 0, 0)
    return (d - j2000).total_seconds() / 86400.0


def moon_longitude(date_str: str) -> float:
    """月の平均黄経（度, 0-360）を簡易計算。出生時刻は正午JST(=03:00 UT想定)で近似。"""
    d = datetime.strptime(date_str, "%Y-%m-%d")
    # 正午JST ≒ 03:00 UT。簡易につき時刻補正は省略（平均黄経の近似精度内）
    days = _days_since_j2000(d)
    L = 218.316 + 13.176396 * days  # 月の平均黄経（低精度公式）
    return (L + SHUKU_OFFSET_DEG) % 360.0


def honmei_shuku(date_str: str) -> str:
    """生年月日から本命宿を返す（決定的）。"""
    idx = int(moon_longitude(date_str) // _SPAN) % 27
    return SHUKU_27[idx]


def _shuku_distance(a: str, b: str) -> int:
    """27宿サイクル上の最短距離（0=同宿）。相性の遠近の目安。"""
    ia, ib = SHUKU_27.index(a), SHUKU_27.index(b)
    diff = abs(ia - ib) % 27
    return min(diff, 27 - diff)


# ---------------- 貼り付けテキストの自動読み取り ----------------
# DM/LINEで届いた文章（生年月日＋①状況②期間のテンプレ回答＋自由文）をそのまま解析する。

# 全角の数字・区切りを半角へ寄せてから解析する
_Z2H = str.maketrans("０１２３４５６７８９．，／－", "0123456789.,/-")

# 区切りの揺れを許容（記号のほか「1981 12 29」のようなスペース区切りも可）。
# 生まれ年は〜2019に限定（本文中の出来事の日付「2024年…」を誤って拾わないため）
_YEAR = r"(19[4-9]\d|200\d|201\d)"
_SEP1 = r"(?:\s*[年/\-\.,，、･・]\s*|\s+)"
_SEP2 = r"(?:\s*[月/\-\.,，、･・]\s*|\s+)"
_DATE_RE = re.compile(
    rf"{_YEAR}{_SEP1}(1[0-2]|0?[1-9]){_SEP2}(3[01]|[12]\d|0?[1-9])(?!\d)\s*日?"
)
# 「1973.0908」「19730908」のように月日が4桁でくっついた書き方
_DATE_COMPACT_RE = re.compile(
    rf"{_YEAR}(?:\s*[/\-\.,，、･・]\s*)?(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(?!\d)"
)


def _find_birthdates(text: str) -> list[str]:
    """本文から生年月日を出現順に最大2件（1つ目=相談者、2つ目=彼）。表記揺れを広く許容する。"""
    hits: list[tuple[int, str, str, str]] = []
    for pat in (_DATE_RE, _DATE_COMPACT_RE):
        for m in pat.finditer(text):
            hits.append((m.start(), m.group(1), m.group(2), m.group(3)))
    hits.sort()
    dates, used = [], []
    for pos, y, mo, d in hits:
        if any(abs(pos - u) < 6 for u in used):
            continue  # 同じ箇所への二重マッチは除外
        used.append(pos)
        dates.append(f"{y}-{int(mo):02d}-{int(d):02d}")
    return dates[:2]
# 状況は長い語から先に判定（「急に冷められた」を「冷められた」より優先）
_STATUS_PATTERNS = [
    ("音信不通", "音信不通"),
    ("既読スルー", "既読スルー"),
    ("未読スルー", "既読スルー"),
    ("急に冷められた", "急に冷められた"),
    ("冷められた", "急に冷められた"),
    ("冷たくなった", "急に冷められた"),
    ("別れ話", "別れ話の後"),
    ("片思い", "片思いで進展なし"),
    ("復縁", "復縁したい"),
]


def find_birthdates(text: str) -> list[str]:
    """本文から生年月日を出現順に最大2件抽出（公開API。LINEボット等から使う）。"""
    return _find_birthdates((text or "").translate(_Z2H))


def parse_free_input(text: str) -> dict:
    """貼り付け文から 生年月日2件（1つ目=相談者、2つ目=彼）・状況・期間 を読み取る。"""
    text = (text or "").strip().translate(_Z2H)
    dates = _find_birthdates(text)
    # 期間の判定は、日付表記（6月13日 等）の「3日」を誤検知しないよう日付を除いた文で行う
    stripped = _DATE_COMPACT_RE.sub(" ", _DATE_RE.sub(" ", text))
    # 複数の状況語があるときは、本文で先に出てくるもの（=①で本人が選んだ回答）を採用
    found = [(stripped.find(pat), canon) for pat, canon in _STATUS_PATTERNS if pat in stripped]
    status = min(found)[1] if found else ""
    if re.search(r"[〜~]?\s*3\s*日", stripped):
        period = "〜3日"
    elif re.search(r"[〜~]?\s*2\s*週間", stripped):
        period = "〜2週間"
    elif re.search(r"[1１]?\s*[ヶケヵか][月]|ヶ月以上", stripped):
        period = "1ヶ月以上"
    else:
        period = ""
    return {
        "me": dates[0] if dates else "",
        "him": dates[1] if len(dates) > 1 else "",
        "status": status,
        "period": period,
    }


