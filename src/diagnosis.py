"""無料診断エンジン（椿姉）。

ファネルの心臓：状況＋二人の生年月日 → 宿曜で本命宿を算出 → 椿姉の声で鑑定文を生成。
わざと7割で止め、「動くべきか/待つべきか」はLINEに誘導する（オープンループ）。

設計方針:
- 本命宿の算出はここで決定的に行う（同じ生年月日なら必ず同じ宿）。
- 宿曜の"相性の解釈"はLLM（椿姉）に委ねる。宿名と状況を渡し、椿姉の知識で相性を語らせる。
- 月の平均黄経による簡易計算のため、公式宿曜表と数日ずれることがある。
  SHUKU_OFFSET_DEG で校正可能（既知の生年月日で公式サイトと突き合わせて調整）。

CLI:
  python -m src.main diagnose --me 1992-05-03 --him 1990-11-21 \
      --status 音信不通 --period 2週間
"""
from __future__ import annotations

from datetime import datetime

from .config import active_profile
from .llm import complete

# 二十七宿（昴宿から始まる標準配列）
SHUKU_27 = [
    "昴宿", "畢宿", "觜宿", "参宿", "井宿", "鬼宿", "柳宿", "星宿", "張宿",
    "翼宿", "軫宿", "角宿", "亢宿", "氐宿", "房宿", "心宿", "尾宿", "箕宿",
    "斗宿", "女宿", "虚宿", "危宿", "室宿", "壁宿", "奎宿", "婁宿", "胃宿",
]
_SPAN = 360.0 / 27.0  # 1宿あたりの黄経幅（約13.33度）

# 校正用オフセット（度）。公式宿曜表に合わせてここを調整する。
SHUKU_OFFSET_DEG = 0.0


def _days_since_j2000(d: datetime) -> float:
    """J2000.0(2000-01-01 12:00 UT)からの経過日数。出生時刻不明のため正午JST扱い。"""
    j2000 = datetime(2000, 1, 1, 12, 0, 0)
    return (d - j2000).total_seconds() / 86400.0


def moon_longitude(date_str: str) -> float:
    """月の平均黄経（度, 0-360）を簡易計算。出生時刻は正午JST(=03:00 UT想定)で近似。"""
    d = datetime.strptime(date_str, "%Y-%m-%d")
    # 正午JST ≒ 03:00 UT。簡易につき時刻補正は省略（平均黄経の近似精度内）
    days = _days_since_j2000(d)
    L = 218.316 + 13.176396 * days  # 月の平均黄経（低精度公式）
    return (L + SHUKU_OFFSET_DEG) % 360.0


def honmei_shuku(date_str: str) -> str:
    """生年月日から本命宿を返す（決定的）。"""
    idx = int(moon_longitude(date_str) // _SPAN) % 27
    return SHUKU_27[idx]


def _shuku_distance(a: str, b: str) -> int:
    """27宿サイクル上の最短距離（0=同宿）。相性の遠近の目安。"""
    ia, ib = SHUKU_27.index(a), SHUKU_27.index(b)
    diff = abs(ia - ib) % 27
    return min(diff, 27 - diff)


DIAG_SYSTEM = """あなたは恋愛・復縁専門の占い師「椿姉（つばきねえ）」。宿曜占星術で「彼の本音」を視る、関西弁・毒舌・姉御肌の鑑定士。
相談者（女性）に向けて、無料診断の鑑定文を書く。

声のルール:
- 一人称「ウチ」、相手は「あんた」。関西弁・タメ口（〜や／〜やで／〜してみ／〜知ってるで）
- 慰めの嘘は言わん。本音をズバッと。ただし最後は突き放さず受け止める（厳しさ7・愛3）

鑑定文の構成（この順で、全体250〜400字・プレーンテキスト）:
1. 相手の状況に一突き（共感しつつ本音を一言）
2. 彼の性質を断定的に語る。「こういうタイプの男や」と、誰が読んでも分かる日常の言葉で具体的に描く
3. 二人の相性（縁の質）を平易に語る。「噛み合う二人」「こじれると長引く縁」のように普通の人が分かる言い方で
4. 今そういう状況になっている「彼の本音」を“7割だけ”明かす（核心の手前まで）。ただし安心させて終わらせない。「彼はまだ気にしてる」等で安心しきらせず、必ず一抹の不安（このまま放置したら…）を残す
5. 締め＝オープンループ＋“期限”の不安：「彼の気持ちには“動く時期”があって、それを逃すと縁は遠のく。あんたの場合その波が近い——でも、それがいつで、あんたが何をどう動けばええかは、ちゃんと視んと言えん」と書く。具体的な処方箋（どうすべきか/いつ/何を送るか）は絶対に書かず、“今動かんと手遅れ”の時間の圧をかけてLINEへ誘導する。LINE登録リンクが渡されたら、本文の最後にそのURLをそのまま1行で載せる

厳守:
- 【最重要】専門用語を本文に一切出さない。『宿曜』という占術名、宿の名前（張宿・房宿・箕宿など）、「距離9」、関係名（友引宿・命・業・胎など）は禁止。占いの裏付けは「ウチが視たところ」程度にとどめ、中身は全部、誰でも分かる日常の言葉に翻訳して伝える
- 【最重要】満足させて終わらない。「彼はまだあんたを想ってる」で安心しきらせると客は動かなくなる。安心は一瞬だけ、最後は必ず“期限の不安”で締める
- 【最重要】処方箋（具体的な行動・かける言葉・動くべき日やタイミング）は無料では絶対に書かない。それは有料で渡す核。「待てばいい」「そのうち戻る」と受け取れる書き方もしない
- 復縁や結果を保証しない（「必ず戻る」等は書かない）。病気・健康・金運の断定はしない。装飾記号(マークダウン)は使わない
- 絵文字は締めに🌙を1つだけ。出力は鑑定文のみ"""


MONTHLY_SYSTEM = """あなたは恋愛・復縁専門の占い師「椿姉（つばきねえ）」。月額会員向けに「今月の運気鑑定」を書く。
会員はすでにお金を払ってくれてる常連。だから無料診断と違い、出し惜しみせず“安心と前進感”を渡しきる。

声: 一人称「ウチ」、相手は「あんた」。関西弁・タメ口。毒舌は控えめ、姉御の温かさ多めで。

構成（全体250〜400字・プレーンテキスト）:
1. 今月の二人の運気の流れを、日常語で（彼の今の心の状態にも触れる）
2. 今月、彼との関係で「動いてええ時期／控えた方がええ時期」の目安を具体的に（上旬・中旬・下旬の感覚で）
3. 今月の開運アクション（3秒〜1分で終わる楽なもの。頑張らせない＝“やった気・前進感”を出す）
4. 最後に椿姉の寄り添い一言（来月もまた視るで、的な継続の安心）

厳守:
- 『宿曜』という占術名や、宿の名前・距離・関係名は本文に一切出さない。中身は日常語に翻訳する
- 復縁・結果を保証しない／過度に不安を煽らない／病気・健康・金運の断定はしない
- 無料診断のように“続きはLINEで”と引っ張らない。もう会員やから、ここで価値を渡しきる
- 装飾記号(マークダウン)は使わない。絵文字は締めに🌙を1つだけ。出力は鑑定文のみ"""


def generate_monthly(me_birth: str, him_birth: str, worry: str = "",
                     month_label: str = "今月") -> dict:
    """月額会員向けの『今月の運気鑑定』を生成する（価値を渡しきる版）。
    返り値: {me_shuku, him_shuku, reading}
    """
    me_s = honmei_shuku(me_birth)
    him_s = honmei_shuku(him_birth)
    user = (
        f"月額会員向けに「{month_label}の運気鑑定」を書いてください。\n"
        f"【相談者の今の悩み・状況】{worry.strip() or '特に指定なし（二人の全体運で視る）'}\n\n"
        "--- 以下は内部参考（宿曜の算出結果）。専門用語なので本文には絶対に出さず、"
        "性質や流れの“中身”だけを日常語に翻訳して使うこと ---\n"
        f"・相談者の本命宿: {me_s}\n"
        f"・彼の本命宿: {him_s}\n"
        "----------------------------------------------------------------\n\n"
        f"{month_label}の二人の運気の流れ、動いてええ時期/控える時期の目安、{month_label}の開運アクション、"
        "最後に寄り添いの一言、の順で。会員向けやから出し惜しみせず、安心と前進感を渡しきること。"
    )
    reading = complete(MONTHLY_SYSTEM, user, max_tokens=700, temperature=0.9).strip()
    return {"me_shuku": me_s, "him_shuku": him_s, "reading": reading}


CONSULT_SYSTEM = """あなたは恋愛・復縁専門の占い師「椿姉（つばきねえ）」。相談し放題の月額会員から届いた相談に、椿姉として返信する。
会員は課金してくれてる常連。出し惜しみせず、あたたかく・本音で・具体的に寄り添う。

声: 一人称「ウチ」、相手は「あんた」。関西弁・タメ口。毒舌は控えめ、姉御の温かさ多めで。

やること:
1. 相談内容に正面から答える（彼の心理・今の状況を宿曜の視点で、日常語で）
2. 前回までのやりとり（あれば）を踏まえ、続きとして話す（「前も言うたけどな」等、覚えてる感を出す）
3. 具体的に「今どうしたらええか」の一歩を渡す（ただし無理な努力は課さない。楽に前進感が出るもの）
4. 最後に一言、あたたかく背中を押す

厳守:
- 『宿曜』という占術名や、宿の名前・距離・関係名は本文に出さない。中身は日常語に翻訳する
- 復縁・結果を保証しない／過度に不安を煽らない／病気・健康・金運の断定はしない
- 会員やから、無料診断のように「続きはLINEで」と引っ張らない。ここでちゃんと応えきる
- 装飾記号(マークダウン)は使わない。絵文字は締めに🌙を0〜1個。出力は返信本文のみ"""


def generate_consult(me_birth: str, him_birth: str, message: str, history: str = "") -> dict:
    """相談し放題の会員から届いた相談への、椿姉の返信を生成する。
    history は直近のやりとり要約（継続感を出す用）。返り値: {me_shuku, him_shuku, reply}
    """
    me_s = honmei_shuku(me_birth)
    him_s = honmei_shuku(him_birth)
    user = (
        "月額会員から届いた相談に、椿姉として返信してください。\n\n"
        f"【会員から届いた相談】{message.strip()}\n"
        + (f"\n【前回までのやりとり（継続の参考）】\n{history.strip()}\n" if history.strip() else "")
        + "\n--- 内部参考（宿曜の算出結果。専門用語なので本文に出さず、中身だけ日常語に翻訳） ---\n"
        f"・会員の本命宿: {me_s}\n"
        f"・彼の本命宿: {him_s}\n"
        "----------------------------------------------------------------\n\n"
        "相談に正面から答え、前回の流れがあれば踏まえ、具体的な一歩を渡して、あたたかく締めてください。"
    )
    reply = complete(CONSULT_SYSTEM, user, max_tokens=700, temperature=0.9).strip()
    return {"me_shuku": me_s, "him_shuku": him_s, "reply": reply}


def generate_reading(me_birth: str, him_birth: str, status: str, period: str,
                     details: str = "") -> dict:
    """無料診断の鑑定文を生成して返す。
    details は相談者の自由記述（例: 未読無視が続いてる／既読はつくが返信なし 等）。
    返り値: {me_shuku, him_shuku, distance, reading}
    """
    me_s = honmei_shuku(me_birth)
    him_s = honmei_shuku(him_birth)
    dist = _shuku_distance(me_s, him_s)
    nearness = "近い（縁が濃い）" if dist <= 3 else ("中くらい" if dist <= 9 else "遠い（試される縁）")

    profile = active_profile()
    line_url = profile.get("line_url", "")
    user = (
        "次の相談者に、椿姉として無料診断の鑑定文を書いてください。\n"
        "※相談者はすでに生年月日を送ってくれている。生年月日やDMを再度要求せず、続きはLINEへ誘導すること。\n\n"
        f"【相談者の状況】{status}\n"
        f"【最後の連絡からの期間】{period}\n"
        + (f"【相談者が書いた具体的な状況】{details}\n" if details.strip() else "")
        + "\n"
        "--- 以下は鑑定の内部参考（宿曜の算出結果）。専門用語なので本文には絶対に出さず、"
        "性質や相性の“中身”だけを日常語に翻訳して使うこと ---\n"
        f"・相談者の本命宿: {me_s}\n"
        f"・彼の本命宿: {him_s}\n"
        f"・二人の宿の距離: {dist}（{nearness}）\n"
        "----------------------------------------------------------------\n\n"
        "彼の性質と二人の相性を、専門用語を使わず誰でも分かる言葉で具体的に語り、"
        "彼が今その状況になっている本音を7割明かし、残り（本音の核心と動き時）はLINEで視ると締めてください。\n"
        + ("相談者が具体的な状況を書いている場合は、その内容に正面から触れ、"
           "その状況ならではの彼の心理を語ってカスタマイズ感を出すこと。\n" if details.strip() else "")
        + (f"【LINE登録リンク】{line_url} ← 鑑定文の最後に、椿姉の言葉で「続きはLINEで視たる」と促してこのURLを1行で載せる"
           if line_url else "")
    )
    reading = complete(DIAG_SYSTEM, user, max_tokens=700, temperature=0.9).strip()
    return {"me_shuku": me_s, "him_shuku": him_s, "distance": dist, "reading": reading}
