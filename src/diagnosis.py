    ("復縁", "復縁したい"),
    # ★2026-08-13：人に言えん関係。診断の選択肢に足したので、
    #   自由入力からも同じラベルに寄せる（表記ゆれをここで吸収する）
    ("人に言えない関係", "人に言えない関係"),
    ("人に言えん関係", "人に言えない関係"),
