def soften_rude(text: str) -> str:
    """相談者の好きな相手を雑に呼ぶ語を、意味を変えずに直す。

    ここが唯一の正規版。生成系（投稿・LINE返信・会員返信・鑑定書）は全部ここを通す。
    """
    for a, b in _RUDE_PRONOUNS.items():
        text = text.replace(a, b)
    text = _RUDE_THAT_MAN_RE.sub("彼", text)
    kana = {"アンナ": "あんな", "コンナ": "こんな", "ソンナ": "そんな"}
    return _RUDE_SUCH_MAN_RE.sub(lambda m: f"{kana.get(m.group(1), m.group(1))}人", text)

