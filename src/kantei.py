# 出力してください／ユーザーがチェックをつけたら…」という、鑑定書と無関係な指示ブロックが
# 53段落ぶん生成された（AI署名ガードはモデル名だけを落とし、この塊は素通りした）。
# 椿は「ユーザー」「フォーマット」「出力してください」といった語を絶対に使わんので、
# これらが出た段落から後ろは、まるごと切り落とす。
_INSTRUCTION_LEAK_RE = re.compile(
    # 指示文テンプレートが丸ごと混入するパターン
    r"出力してください|フォーマットで出力|チェックリスト|チェックボックス|"
    r"ユーザーが|ユーザーは|ユーザーの回答|^\s*ステップ\s*$|^\s*参照\s*$|^\s*目的\s*$|"
    r"^\s*出力\s*$|セクション\d|一問一答|以下のフォーマット|次のセクション|"
    # 生成モデルの自己修正コメント。実害3件（みき・りよ・ゆり）。
    # 「※締めのは最終章のみの指定でしたので、この章では取り下げます。以下、修正版の末尾です」
    # 「（続く）」のように、本文の途中に注釈を挟んで書き直しを始めてまう
    r"^\s*※|修正版|再掲します|取り下げます|の指定でしたので|"
    r"^\s*（続く）\s*$|^\s*\(続く\)\s*$|以下、正しい|書き直します",
    re.M,
)


# 生成モデルが「自分の作業」を実況してまう注記。椿は敬体を使わんので、
# 括弧で閉じた注記か、ですます調で終わる段落に運用語彙が入っとったら、それは本文やない。
# ★実害（2026-08-06・ともこさん）：第三章の末尾に、こういうんが3つ並んで納品直前まで残った。
#   「（※締めの月は本来最終章用やが、指定に従い本章末には付けません——という但し書きは不要のため削除）」
#   「（※重複配慮のためこの章では月マークは付けないこととします。）」
#   「上の運用注記は不要なので、ここまでを本章の本文とします。」
#   どれも `^\s*※` に当たらん（括弧で始まる）ので、既存のガードを素通りした。
_META_VOCAB_RE = re.compile(
    r"指定に従い|指定でした|但し書き|運用注記|本章|月マーク|重複配慮|"
    r"本文とします|以上が本文|付けません|付けないこと|不要のため|字数の都合"
)


# 生成が章の終わりで崩れて、まったく無関係な文字列を吐き出すことがある。
# ★実害（2026-08-06・ふうさん）：第七章の本文が終わったあと、こういうんが6段落続いた。
#   「Copyright © 2025 菜箸.jp」
#   「Warning: Undefined variable $show_prompt in /home/dst/.../prompt.php on line 82」
#   「Deployed on Vercel<br>」
#   よそのサイトのフッターとPHPのエラー文や。これが有料の納品PDFに入っとった。
#   さらに第三章・第五章の末尾には、英語の独り言も出た。
#   「Wait, let me correct — I should not preview the next chapter's content」
#   「Read more informal — you can do this.」
# 椿の鑑定書は、ほぼ全部が日本語や。だから「ラテン文字の割合」で見るのがいちばん確実。
# LINE のような固有名詞は本文にも出るので、含むかどうかやのうて、割合で判定する。
_WEB_JUNK_RE = re.compile(
    r"(?i)copyright|©|warning:\s*undefined|fatal error|deployed on|"
    r"\.php|\bvercel\b|<br\s*/?>|https?://|www\.|on line \d+|\$[a-z_]{3,}"
)
# 日本語で書かれた自己訂正。「さっきのは無し」と言うて書き直しにかかるやつ
_SELF_CORRECT_RE = re.compile(
    r"訂正させて|今のは無し|さっきのは無し|上の.{0,8}は(?:無視|不要)|"
    r"書き直させて|やっぱりこっち|以下に差し替え"
)


def _latin_ratio(text: str) -> float:
    """本文に占めるラテン文字の割合。日本語の鑑定書なら、ここは限りなく0に近い。"""
    body = re.sub(r"\s", "", text)
    if not body:
        return 0.0
    return sum(1 for ch in body if "a" <= ch.lower() <= "z") / len(body)


# 英文らしい連なり。三語以上が空白で繋がっとるもんを英語とみなす。
# 「彼のLINEを見た」の LINE は一語なので当たらん。固有名詞は本文にも出るから、
# 含むかどうかやのうて「文になっとるか」で見る。
_ENGLISH_RUN_RE = re.compile(r"[A-Za-z][A-Za-z',.\-]*(?:\s+[A-Za-z][A-Za-z',.\-]*){2,}")


def _is_foreign_junk(block: str) -> bool:
    """章の本文やないもんが紛れ込んどったら True。"""
    b = block.strip()
    if not b:
        return False
    if _WEB_JUNK_RE.search(b) or _SELF_CORRECT_RE.search(b):
        return True
    # 英語の独り言。三語以上が繋がって十五字以上あったら、それは本文やない
    if any(len(m) >= 15 for m in _ENGLISH_RUN_RE.findall(b)):
        return True
    # 長めの段落でラテン文字の割合が高い（短文は LINE 等で跳ねるので対象外）
    if len(re.sub(r"\s", "", b)) >= 40 and _latin_ratio(b) > 0.15:
        return True
    if re.search(r"[ぁ-んァ-ヶ一-龥]", b):
        return False
    # ここから先は日本語が一文字も無い段落。
    # ただし章の締めに置く絵文字だけの行は本文の一部やから、これは残す
    return not re.fullmatch(r"[🌙⛩️🌈✨💫🍀\s]{1,4}", b)


def _is_meta_note(block: str) -> bool:
    """段落まるごとが「生成側の注記」やったら True。本文の途中は巻き込まん。"""
    b = block.strip()
    if not b or not _META_VOCAB_RE.search(b):
        return False
    wrapped = b[:1] in "（(" and b[-1:] in "）)"
    polite = re.search(r"(?:します|ます|ました|ません|です|でした)。?$", b) is not None
    return wrapped or polite


def strip_instruction_leak(text: str) -> str:
    """指示文の混入を落とす。段落は空行区切り。

    三段構え。
    ①段落まるごとが生成側の注記やったら、その段落だけ落とす（前後の本文は残す）。
    ②日本語やないもん（よそのサイトのフッター、PHPのエラー、英語の独り言）が出てきたら、
      そこで生成が崩れとる証拠やから、そこから後ろを全部落とす。
    ③指示文テンプレートの混入や書き直しが始まっとっても、同じく後ろを全部落とす。
      途中で切れても、章が丸ごと壊れるより遥かにマシ。呼び出し側で警告を出す。
    """
    blocks = [b for b in re.split(r"\n\s*\n", text) if not _is_meta_note(b)]
    for i, b in enumerate(blocks):
        if _is_foreign_junk(b) or _INSTRUCTION_LEAK_RE.search(b):
            return "\n\n".join(blocks[:i]).rstrip()
    return "\n\n".join(blocks).rstrip()


def strip_markdown(text: str) -> str:
    """顧客に渡す文面からMarkdownの装飾記号を落とす。

    LINEもPDFもMarkdownを解釈せんので、`**強調**` はそのまま記号ごと表示されてまう。
    椿が生身の鑑定士やと信じてもらうのが土台なので、機械が書いた形跡は一つも残さん。
    ★2026-08-04: 納品文の生成経路にだけこのガードが無かった（プロンプト頼みやった）。
    """
    text = text.replace("**", "").replace("__", "")
    text = re.sub(r"(?m)^\s{0,3}#{1,6}\s+", "", text)      # 見出し
    text = re.sub(r"(?m)^\s{0,3}[*\-]\s+", "・", text)     # 箇条書き→・
    text = text.replace("*", "").replace("＊", "")
    return re.sub(r"[ \t]{2,}", " ", text)


def generate_delivery_note(name: str, chapters: list[dict], details: str) -> str:
    """鑑定書と一緒にLINEへ送る【納品文】を生成する。

    鑑定書だけ渡して終わりにすると、感想が返ってこず月詠みの案内に進めない。
    店主が手で書き起こす運用は実際に抜けたことがあるので、生成と同時に必ず出す。
    """
    toc = "\n".join(f"第{_KANJI_NUM[i]}章 {c['title']}" for i, c in enumerate(chapters))
    digest = "\n\n".join(
        f"【第{_KANJI_NUM[i]}章 {c['title']}】\n{c['body'][:500]}…" for i, c in enumerate(chapters)
    )
    user = (
        f"=== 相談者の呼び名 ===\n{name}\n\n"
        f"=== 相談者から届いた相談文（全文。ここから一番知りたかった問いと、"
        f"この人が自分でやっていた良い一手を拾う） ===\n{details}\n\n"
        f"=== 出来上がった鑑定書の目次 ===\n{toc}\n\n"
        f"=== 各章の書き出し（何を書いたかの参考） ===\n{digest}\n\n"
        "この鑑定書に添える【納品文】を書いてください。本文だけを出力してください。"
    )
    text = complete(DELIVERY_SYSTEM, user, max_tokens=1600, temperature=0.7).strip()
    return _fix_delivery_closing(strip_ai_leak(strip_markdown(strip_jargon(text))))


# 納品文の締めは、一字一句この四行で固定する。
# ★2026-08-06：ここに「月詠み」という商品名を出したらあかん。相談者はまだその名前を知らん。
#   知らん名前を急に出されると、案内やのうて売り文句に見えてまう。
#   名前を出してええのは、感想が返ってきてから送る、月額の案内の便からや。
DELIVERY_CLOSING = (
    "ほんで最後に一個だけ言うとくな。\n"
    # ★★2026-08-20：ここの一人称は「私」や。「ウチ」は椿の一人称やから、
    #   相談者の心の声に使うたら、誰が喋っとるんか分からんようになる。
    "読んだあとに出てくる「で、私はこれからどう動いたらええん？」——\n"
    # ★★2026-08-20：「別のプラン」も商品を名指ししとることになるんで、「場」に戻した。
    #   funnel ②-1 の指定は「その先の一手を受けとる場は、ちゃんと別に用意してある」や。
    "そこから先の細かい一手を受けとる場は、ちゃんと別に用意してある。\n"
    "そういう場があるいうことだけ、今のうちに置いとくわ🌙"
)


def _fix_delivery_closing(text: str) -> str:
    """納品文の締めを、決まった四行に必ず差し替える。

    プロンプトで「そのまま書け」と言うても、生成は必ず言い換えてくる。
    商品名（月詠み）が一語でも漏れたら、そこで納品文の温度が壊れるので、
    締めの段落は文章として作らせず、コードで置き換える。
    """
    blocks = re.split(r"\n\s*\n", text.strip())
    # 「月詠み」や線引きに触れとる末尾の段落を落としてから、決め打ちの締めを足す
    while blocks and re.search(r"月詠み|別のプラン|どう動いたらええ|これどうしたら", blocks[-1]):
        blocks.pop()
    body = "\n\n".join(blocks).rstrip()
    # 本文の途中に商品名が残っとったら、そこも伏せる
    body = body.replace("椿の月詠み", "別に用意してある場").replace("月詠み", "別に用意してある場")
    return f"{body}\n\n{DELIVERY_CLOSING}"


# 鑑定文を組み立てる時にだけ使う言葉。これが本文に出たら、生成が指示ごと書き写した証拠や。
# 客に渡る紙に一語でも出たら、椿が生身やという前提が壊れる（04_avoid の最上位ルール）。
_PROMPT_LEAK_RE = re.compile(
    r"===\s*今回書く章\s*==="
    r"|続けて次の章を書いて"
    r"|章タイトル\s*[:：]"
    r"|この章で書くこと\s*[:：]"
    r"|目安の分量\s*[:：]"
    r"|本文だけを出力"
    r"|【この章でも守ること】"
    r"|===\s*(?:相談者|内部参考|ここまでの章)\s*==="
)


def _assert_clean(chapters: list[dict]) -> None:
    """PDFを組む直前の最後の砦。章ごとのガードを抜けたもんが残ってへんか、もう一遍見る。

    ここで止めるんは、出てもうたら取り返しがつかんからや。
    有料の納品物に、よそのサイトのフッターやPHPのエラーが載ったら、それで信用は終わる。
    """
    dirty: list[str] = []
    for c in chapters:
        for b in re.split(r"\n\s*\n", c["body"]):
            if _is_foreign_junk(b) or _is_meta_note(b):
                dirty.append(f"【{c['title']}】{b.strip()[:90]}")
        # ★2026-08-12：上の段落単位の検査だけでは足りんかった。
        #   生成が暴走して、次の章の指示文を本文に「地続きで」書き足した事故が起きた
        #   （綾美さんの第四章。空行が無いので段落として切り出されず、素通りした）。
        #   組み立てに使う言葉が本文に出た時点で、それは事故や。全文を端から見る。
        m = _PROMPT_LEAK_RE.search(c["body"])
        if m:
            i = max(0, m.start() - 40)
            dirty.append(f"【{c['title']}】組み立て用の指示が混入: …{c['body'][i:m.end() + 60]}…")
    if dirty:
        print("\n🛑 納品を止めた。章に本文やないもんが残っとる：")
        for d in dirty:
            print(f"   ・{d}")
        raise RuntimeError(
            f"鑑定書に本文以外の混入が {len(dirty)} 件残っている。"
            "PDFは作らずに止めた。生成し直すこと。"
        )


# ★★★2026-10-01 新設：処方箋の時期が【もう過ぎとる】のを機械で捕まえる。
#
#   実害（りささんの回）：今日が10月1日やのに、一手目の時期が
#   「お盆が明けてから、八月の終わりまでの間」。会う話を出す目安も「九月の終わりから十月あたり」。
#   ★どっちも過ぎとる。読んだ人は「今10月やのに八月に送れ言われても」となる。
#   ★★内部の材料には「今日の日付」を渡してあった。★渡すだけでは守られん。
#     この一ヶ月で何回も証明された話や。せやから機械で見る。
#
#   ★見るんは【これからの動きを指しとる文】だけや。
#     「2024年8月に会いに来た」みたいな過去の出来事は、年が付いとるか、
#     動きの語（送る・投げる・動く・誘う等）が無いかで外れる。
_FUTURE_WORDS = ("送", "投げ", "動く", "動き", "誘", "出す", "置く", "連絡", "一手",
                 "切り出", "会う話", "待つ", "まで", "目安")
_MONTH_RE = re.compile(r"(?<!年)(?:([1-9]|1[0-2])|([一二三四五六七八九]|十[一二]?))月")
# ★名前は _KANJI_NUM と分ける。あっちは章番号用の【並び】で、ここは月の【読み替え】や。
#   ★★一回ここを _KANJI_NUM で書いて、章番号の方を上書きして鑑定書の生成を丸ごと壊した。
_KANJI_TO_MONTH = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7,
                   "八": 8, "九": 9, "十": 10, "十一": 11, "十二": 12}
_SEASON_MONTH = {"お盆": 8, "年末": 12, "年明け": 1, "年始": 1}


def check_past_timing(chapters: list[dict], today: str) -> list[str]:
    """これからの動きに、もう過ぎた月を書いてへんか見る。戻り値は警告の一覧。"""
    t = datetime.strptime(today, "%Y-%m-%d")
    out: list[str] = []
    for c in chapters:
        for sent in re.split(r"(?<=[。\n])", str(c.get("body") or "")):
            if not any(w in sent for w in _FUTURE_WORDS):
                continue
            if re.search(r"\d{4}年", sent):      # 年が書いてあるんは過去の出来事や
                continue
            months = set()
            for m in _MONTH_RE.finditer(sent):
                # ★★2026-10-05：「九月二十日」みたいに【日にち付き】は、過ぎた出来事の話や。
                #   ★のりこさんの回で三件とも誤検出した（「九月二十日に長文を送って、返事を待っとる」）。
                #   ★★嘘の警告が続いたら、本物の警告まで流して見るようになる。
                #   ★★★処方箋の時期は「八月の終わりまで」「十月あたり」みたいに【幅】で書く。
                #     日にちが付いとる月は、ここでは見ん。
                if re.match(r"[0-9０-９一二三四五六七八九十]{1,3}日", sent[m.end():]):
                    continue
                months.add(int(m.group(1)) if m.group(1) else _KANJI_TO_MONTH.get(m.group(2), 0))
            for k, mon in _SEASON_MONTH.items():
                if k in sent:
                    months.add(mon)
            # ★今月より前の月を指しとったら、過ぎとる疑い。
            #   ★★年をまたぐ先（1月〜3月を10月に書く等）は、まだ来とらんので外す。
            for mon in sorted(months):
                if 1 <= mon < t.month and (t.month - mon) <= 6:
                    out.append(f"{c.get('title') or c.get('key')}：「{mon}月」は過ぎとる"
                               f"（今日は{t.month}月）→ {sent.strip()[:60]}")
                    break
    return out


def make_kantei(name: str, me_birth: str, him_birth: str, details: str,
                today: str | None = None) -> dict:
    """鑑定書を生成してPDFまで出力。{html, pdf, chars} を返す。"""
    today = today or datetime.now().strftime("%Y-%m-%d")
    OUT_DIR.mkdir(exist_ok=True)
    print(f"🖋 鑑定文を生成中（{len(CHAPTERS)}章）…")
    chapters = generate_chapters(name, me_birth, him_birth, details, today=today)
    total = sum(len(c["body"]) for c in chapters)
    _assert_clean(chapters)
    # ★処方箋の時期が過ぎとらんか。止めはせんが、必ず画面に出す（見落としを防ぐ）
    _late = check_past_timing(chapters, today)
    if _late:
        print(f"⚠ 時期の点検 {len(_late)}件：もう過ぎた月を指しとる。直してから送ること")
        for x in _late:
            print(f"   ・{x}")
    from .reading_summary import generate as generate_summary
    print("📝 本文から要点ページを作成中…")
    try:
        summary = generate_summary(name, chapters)
    except Exception:
        # 本文8章は生成に金も時間もかかる。要点ページで落ちても捨てん（2026-09-10）
        bak = OUT_DIR / f"章退避_{name}_{today}.json"
        bak.write_text(json.dumps(chapters, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"💾 本文8章は退避した: {bak}")
        raise
    _assert_clean([{"key": "summary", "title": "要点", "body": "\n".join(summary.values())}])
    stem = f"個別鑑定_{name}"
    html_path = OUT_DIR / f"{stem}.html"
    pdf_path = OUT_DIR / f"{stem}.pdf"
    html_path.write_text(build_html(name, chapters, today, summary=summary), encoding="utf-8")
    html_to_pdf(html_path, pdf_path)
    # 納品用にダウンロードフォルダへも必ず置く（LINE公式アプリから添付しやすいように）。
    # ダウンロード側のファイル名は「個別鑑定_名前さん.pdf」（相談者に見える名前なので敬称付き）
    dl_path = Path.home() / "Downloads" / f"個別鑑定_{with_honorific(name)}.pdf"
    shutil.copy2(pdf_path, dl_path)
    print(f"📜 完成: {pdf_path}（本文{total}字）")
    print(f"⬇️ ダウンロードにも配置: {dl_path}")
    # 納品文は「あとで書く」と必ず抜けるので、鑑定書と同時に必ず出す（2026-08-04ルール化）
    print("✍️ 納品文を生成中…")
    note = generate_delivery_note(name, chapters, details)
    note_path = OUT_DIR / f"納品文_{name}.txt"
    note_path.write_text(note, encoding="utf-8")
    print(f"💬 納品文: {note_path}")
    return {"html": str(html_path), "pdf": str(pdf_path), "download": str(dl_path),
            "chars": total, "note": note, "note_path": str(note_path), "summary": summary}


# ---------------- 月詠み（月額会員向けの月次ミニ鑑定書） ----------------
