def _is_foreign_junk(block: str) -> bool:
    """章の本文やないもんが紛れ込んどったら True。"""
    b = block.strip()
    if not b:
        return False
    if _WEB_JUNK_RE.search(b) or _SELF_CORRECT_RE.search(b):
        return True
    # 英語の独り言。三語以上が繋がって十五字以上あったら、それは本文やない
    if any(len(m) >= 15 for m in _ENGLISH_RUN_RE.findall(b)):
        return True
    # 長めの段落でラテン文字の割合が高い（短文は LINE 等で跳ねるので対象外）
    if len(re.sub(r"\s", "", b)) >= 40 and _latin_ratio(b) > 0.15:
        return True
    if re.search(r"[ぁ-んァ-ヶ一-龥]", b):
        return False
    # ここから先は日本語が一文字も無い段落。
    # ただし章の締めに置く絵文字だけの行は本文の一部やから、これは残す
    return not re.fullmatch(r"[🌙⛩️🌈✨💫🍀\s]{1,4}", b)


def _is_meta_note(block: str) -> bool:
    """段落まるごとが「生成側の注記」やったら True。本文の途中は巻き込まん。"""
    b = block.strip()
    if not b or not _META_VOCAB_RE.search(b):
        return False
    wrapped = b[:1] in "（(" and b[-1:] in "）)"
    polite = re.search(r"(?:します|ます|ました|ません|です|でした)。?$", b) is not None
    return wrapped or polite


def strip_instruction_leak(text: str) -> str:
    """指示文の混入を落とす。段落は空行区切り。

    三段構え。
    ①段落まるごとが生成側の注記やったら、その段落だけ落とす（前後の本文は残す）。
    ②日本語やないもん（よそのサイトのフッター、PHPのエラー、英語の独り言）が出てきたら、
      そこで生成が崩れとる証拠やから、そこから後ろを全部落とす。
    ③指示文テンプレートの混入や書き直しが始まっとっても、同じく後ろを全部落とす。
      途中で切れても、章が丸ごと壊れるより遥かにマシ。呼び出し側で警告を出す。
    """
    blocks = [b for b in re.split(r"\n\s*\n", text) if not _is_meta_note(b)]
    for i, b in enumerate(blocks):
        if _is_foreign_junk(b) or _INSTRUCTION_LEAK_RE.search(b):
            return "\n\n".join(blocks[:i]).rstrip()
    return "\n\n".join(blocks).rstrip()


def strip_markdown(text: str) -> str:
    """顧客に渡す文面からMarkdownの装飾記号を落とす。

    LINEもPDFもMarkdownを解釈せんので、`**強調**` はそのまま記号ごと表示されてまう。
    椿が生身の鑑定士やと信じてもらうのが土台なので、機械が書いた形跡は一つも残さん。
    ★2026-08-04: 納品文の生成経路にだけこのガードが無かった（プロンプト頼みやった）。
    """
    text = text.replace("**", "").replace("__", "")
    text = re.sub(r"(?m)^\s{0,3}#{1,6}\s+", "", text)      # 見出し
    text = re.sub(r"(?m)^\s{0,3}[*\-]\s+", "・", text)     # 箇条書き→・
    text = text.replace("*", "").replace("＊", "")
    return re.sub(r"[ \t]{2,}", " ", text)


def generate_delivery_note(name: str, chapters: list[dict], details: str) -> str:
    """鑑定書と一緒にLINEへ送る【納品文】を生成する。

    鑑定書だけ渡して終わりにすると、感想が返ってこず月詠みの案内に進めない。
    店主が手で書き起こす運用は実際に抜けたことがあるので、生成と同時に必ず出す。
    """
    toc = "\n".join(f"第{_KANJI_NUM[i]}章 {c['title']}" for i, c in enumerate(chapters))
    digest = "\n\n".join(
        f"【第{_KANJI_NUM[i]}章 {c['title']}】\n{c['body'][:500]}…" for i, c in enumerate(chapters)
    )
    user = (
        f"=== 相談者の呼び名 ===\n{name}\n\n"
        f"=== 相談者から届いた相談文（全文。ここから一番知りたかった問いと、"
        f"この人が自分でやっていた良い一手を拾う） ===\n{details}\n\n"
        f"=== 出来上がった鑑定書の目次 ===\n{toc}\n\n"
        f"=== 各章の書き出し（何を書いたかの参考） ===\n{digest}\n\n"
        "この鑑定書に添える【納品文】を書いてください。本文だけを出力してください。"
    )
    text = complete(DELIVERY_SYSTEM, user, max_tokens=1600, temperature=0.7).strip()
    return _fix_delivery_closing(strip_ai_leak(strip_markdown(strip_jargon(text))))


# 納品文の締めは、一字一句この四行で固定する。
# ★2026-08-06：ここに「月詠み」という商品名を出したらあかん。相談者はまだその名前を知らん。
#   知らん名前を急に出されると、案内やのうて売り文句に見えてまう。
#   名前を出してええのは、感想が返ってきてから送る、月額の案内の便からや。
DELIVERY_CLOSING = (
    "ほんで最後に一個だけ言うとくな。\n"
    "読んだあとに出てくる「で、ウチはこれからどう動いたらええん？」——\n"
    "その先の細かい一手は、別のプランの方で受けとる。\n"
    "そういう場があるいうことだけ、今のうちに置いとくわ🌙"
)


def _fix_delivery_closing(text: str) -> str:
    """納品文の締めを、決まった四行に必ず差し替える。

    プロンプトで「そのまま書け」と言うても、生成は必ず言い換えてくる。
    商品名（月詠み）が一語でも漏れたら、そこで納品文の温度が壊れるので、
    締めの段落は文章として作らせず、コードで置き換える。
    """
    blocks = re.split(r"\n\s*\n", text.strip())
    # 「月詠み」や線引きに触れとる末尾の段落を落としてから、決め打ちの締めを足す
    while blocks and re.search(r"月詠み|別のプラン|どう動いたらええ|これどうしたら", blocks[-1]):
        blocks.pop()
    body = "\n\n".join(blocks).rstrip()
    # 本文の途中に商品名が残っとったら、そこも伏せる
    body = body.replace("椿の月詠み", "別のプラン").replace("月詠み", "別のプラン")
    return f"{body}\n\n{DELIVERY_CLOSING}"


def _assert_clean(chapters: list[dict]) -> None:
    """PDFを組む直前の最後の砦。章ごとのガードを抜けたもんが残ってへんか、もう一遍見る。

    ここで止めるんは、出てもうたら取り返しがつかんからや。
    有料の納品物に、よそのサイトのフッターやPHPのエラーが載ったら、それで信用は終わる。
    """
    dirty: list[str] = []
    for c in chapters:
        for b in re.split(r"\n\s*\n", c["body"]):
            if _is_foreign_junk(b) or _is_meta_note(b):
                dirty.append(f"【{c['title']}】{b.strip()[:90]}")
    if dirty:
        print("\n🛑 納品を止めた。章に本文やないもんが残っとる：")
        for d in dirty:
            print(f"   ・{d}")
        raise RuntimeError(
            f"鑑定書に本文以外の混入が {len(dirty)} 件残っている。"
            "PDFは作らずに止めた。生成し直すこと。"
        )


def make_kantei(name: str, me_birth: str, him_birth: str, details: str,
                today: str | None = None) -> dict:
    """鑑定書を生成してPDFまで出力。{html, pdf, chars} を返す。"""
    today = today or datetime.now().strftime("%Y-%m-%d")
    OUT_DIR.mkdir(exist_ok=True)
    print(f"🖋 鑑定文を生成中（{len(CHAPTERS)}章）…")
    chapters = generate_chapters(name, me_birth, him_birth, details, today=today)
    total = sum(len(c["body"]) for c in chapters)
    _assert_clean(chapters)
    stem = f"個別鑑定_{name}"
    html_path = OUT_DIR / f"{stem}.html"
    pdf_path = OUT_DIR / f"{stem}.pdf"
    html_path.write_text(build_html(name, chapters, today), encoding="utf-8")
    html_to_pdf(html_path, pdf_path)
    # 納品用にダウンロードフォルダへも必ず置く（LINE公式アプリから添付しやすいように）。
    # ダウンロード側のファイル名は「個別鑑定_名前さん.pdf」（相談者に見える名前なので敬称付き）
    dl_path = Path.home() / "Downloads" / f"個別鑑定_{name}さん.pdf"
    shutil.copy2(pdf_path, dl_path)
    print(f"📜 完成: {pdf_path}（本文{total}字）")
    print(f"⬇️ ダウンロードにも配置: {dl_path}")
    # 納品文は「あとで書く」と必ず抜けるので、鑑定書と同時に必ず出す（2026-08-04ルール化）
    print("✍️ 納品文を生成中…")
    note = generate_delivery_note(name, chapters, details)
    note_path = OUT_DIR / f"納品文_{name}.txt"
    note_path.write_text(note, encoding="utf-8")
    print(f"💬 納品文: {note_path}")
    return {"html": str(html_path), "pdf": str(pdf_path), "download": str(dl_path),
            "chars": total, "note": note, "note_path": str(note_path)}


