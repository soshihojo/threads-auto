# 鑑定書の本文に、指示文・テンプレートの断片が丸ごと混入することがある。
# 実害: 2026-08-05、りよさんの第七章の末尾に「参照／目的／ステップ／チェックリスト形式で
# 出力してください／ユーザーがチェックをつけたら…」という、鑑定書と無関係な指示ブロックが
# 53段落ぶん生成された（AI署名ガードはモデル名だけを落とし、この塊は素通りした）。
# 椿は「ユーザー」「フォーマット」「出力してください」といった語を絶対に使わんので、
# これらが出た段落から後ろは、まるごと切り落とす。
_INSTRUCTION_LEAK_RE = re.compile(
    # 指示文テンプレートが丸ごと混入するパターン
    r"出力してください|フォーマットで出力|チェックリスト|チェックボックス|"
    r"ユーザーが|ユーザーは|ユーザーの回答|^\s*ステップ\s*$|^\s*参照\s*$|^\s*目的\s*$|"
    r"^\s*出力\s*$|セクション\d|一問一答|以下のフォーマット|次のセクション|"
    # 生成モデルの自己修正コメント。実害3件（みき・りよ・ゆり）。
    # 「※締めのは最終章のみの指定でしたので、この章では取り下げます。以下、修正版の末尾です」
    # 「（続く）」のように、本文の途中に注釈を挟んで書き直しを始めてまう
    r"^\s*※|修正版|再掲します|取り下げます|の指定でしたので|"
    r"^\s*（続く）\s*$|^\s*\(続く\)\s*$|以下、正しい|書き直します",
    re.M,
)


# 生成モデルが「自分の作業」を実況してまう注記。椿は敬体を使わんので、
# 括弧で閉じた注記か、ですます調で終わる段落に運用語彙が入っとったら、それは本文やない。
# ★実害（2026-08-06・ともこさん）：第三章の末尾に、こういうんが3つ並んで納品直前まで残った。
#   「（※締めの月は本来最終章用やが、指定に従い本章末には付けません——という但し書きは不要のため削除）」
#   「（※重複配慮のためこの章では月マークは付けないこととします。）」
#   「上の運用注記は不要なので、ここまでを本章の本文とします。」
#   どれも `^\s*※` に当たらん（括弧で始まる）ので、既存のガードを素通りした。
_META_VOCAB_RE = re.compile(
    r"指定に従い|指定でした|但し書き|運用注記|本章|月マーク|重複配慮|"
    r"本文とします|以上が本文|付けません|付けないこと|不要のため|字数の都合"
)


def _is_meta_note(block: str) -> bool:
    """段落まるごとが「生成側の注記」やったら True。本文の途中は巻き込まん。"""
    b = block.strip()
    if not b or not _META_VOCAB_RE.search(b):
        return False
    wrapped = b[:1] in "（(" and b[-1:] in "）)"
    polite = re.search(r"(?:します|ます|ました|ません|です|でした)。?$", b) is not None
    return wrapped or polite


def strip_instruction_leak(text: str) -> str:
    """指示文の混入を落とす。段落は空行区切り。

    二段構え。
    ①段落まるごとが生成側の注記やったら、その段落だけ落とす（前後の本文は残す）。
    ②指示文テンプレートの混入や書き直しが始まっとったら、そこから後ろを全部落とす。
      途中で切れても、章が丸ごと壊れるより遥かにマシ。呼び出し側で警告を出す。
    """
    blocks = [b for b in re.split(r"\n\s*\n", text) if not _is_meta_note(b)]
    for i, b in enumerate(blocks):
        if _INSTRUCTION_LEAK_RE.search(b):
            return "\n\n".join(blocks[:i]).rstrip()
    return "\n\n".join(blocks).rstrip()


def strip_markdown(text: str) -> str:
    """顧客に渡す文面からMarkdownの装飾記号を落とす。

    LINEもPDFもMarkdownを解釈せんので、`**強調**` はそのまま記号ごと表示されてまう。
    椿が生身の鑑定士やと信じてもらうのが土台なので、機械が書いた形跡は一つも残さん。
    ★2026-08-04: 納品文の生成経路にだけこのガードが無かった（プロンプト頼みやった）。
    """
    text = text.replace("**", "").replace("__", "")
    text = re.sub(r"(?m)^\s{0,3}#{1,6}\s+", "", text)      # 見出し
    text = re.sub(r"(?m)^\s{0,3}[*\-]\s+", "・", text)     # 箇条書き→・
    text = text.replace("*", "").replace("＊", "")
    return re.sub(r"[ \t]{2,}", " ", text)


def generate_delivery_note(name: str, chapters: list[dict], details: str) -> str:
    """鑑定書と一緒にLINEへ送る【納品文】を生成する。

    鑑定書だけ渡して終わりにすると、感想が返ってこず月詠みの案内に進めない。
    店主が手で書き起こす運用は実際に抜けたことがあるので、生成と同時に必ず出す。
    """
    toc = "\n".join(f"第{_KANJI_NUM[i]}章 {c['title']}" for i, c in enumerate(chapters))
    digest = "\n\n".join(
        f"【第{_KANJI_NUM[i]}章 {c['title']}】\n{c['body'][:500]}…" for i, c in enumerate(chapters)
    )
    user = (
        f"=== 相談者の呼び名 ===\n{name}\n\n"
        f"=== 相談者から届いた相談文（全文。ここから一番知りたかった問いと、"
        f"この人が自分でやっていた良い一手を拾う） ===\n{details}\n\n"
        f"=== 出来上がった鑑定書の目次 ===\n{toc}\n\n"
        f"=== 各章の書き出し（何を書いたかの参考） ===\n{digest}\n\n"
        "この鑑定書に添える【納品文】を書いてください。本文だけを出力してください。"
    )
    text = complete(DELIVERY_SYSTEM, user, max_tokens=1600, temperature=0.7).strip()
    return _fix_delivery_closing(strip_ai_leak(strip_markdown(strip_jargon(text))))


