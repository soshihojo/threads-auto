def _latin_ratio(text: str) -> float:
    """本文に占めるラテン文字の割合。日本語の鑑定書なら、ここは限りなく0に近い。"""
    body = re.sub(r"\s", "", text)
    if not body:
        return 0.0
    return sum(1 for ch in body if "a" <= ch.lower() <= "z") / len(body)


