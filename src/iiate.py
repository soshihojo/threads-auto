# 表引きに失敗した時の逃げ。ここに落ちたら何も出さん（無理に当てにいかん）
_FALLBACK = ""


def iiate(him_birth: str, status: str = "") -> str:
    """彼の生まれと相談者の状況から、言い当ての一文を表引きで返す。

    生成は一切せん。ここで返るんは TABLE に手で書いた文だけや。
    引けんかったら空文字を返す（無理に当てにいかん）。
    """
    try:
        shuku = honmei_shuku(him_birth)
    except Exception:
        return _FALLBACK
    axis = _AXIS.get((status or "").strip(), _DEFAULT_AXIS)
    return TABLE.get(shuku, {}).get(axis, _FALLBACK)


def coverage() -> dict:
    """表の埋まり具合を返す（検品用）。"""
    axes = ("silence", "break", "slow")
    missing = [(s, a) for s in SHUKU_27 for a in axes if not TABLE.get(s, {}).get(a)]
    return {"total": len(SHUKU_27) * len(axes), "missing": missing}
